CREATE TABLE IF NOT EXISTS scopus_publications (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  publication_title VARCHAR(1000) NOT NULL,
  publication_date VARCHAR(100) NOT NULL DEFAULT '',
  publication_venue VARCHAR(1000) NOT NULL DEFAULT '',
  author_name VARCHAR(255) NOT NULL DEFAULT '',
  school VARCHAR(500) NOT NULL DEFAULT '',
  college VARCHAR(500) NOT NULL DEFAULT '',
  department VARCHAR(500) NOT NULL DEFAULT '',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
